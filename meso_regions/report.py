"""Self-contained HTML patient report for Meso-Regions pipeline outputs.

Generates a single HTML file per patient with:
- static 3-plane overlays,
- an interactive slice viewer (slider / mouse-wheel) where ECE-positive
  regions are composited client-side from an embedded label map — clicking a
  region isolates it and its curve, and vice versa,
- per-superspel signal-intensity curves (clickable SVG) classified in place
  by the published ECE rule,
- the patient-level ECE call.

Everything (images, label maps, curve data) is base64/inline — no external
assets, no JS libraries, no data upload.
"""

import base64
import io
import json
from datetime import datetime
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import nibabel as nib
import numpy as np
import pandas as pd
from PIL import Image

DISCLAIMER = ("Research use only — this report is generated by research "
              "software and must not be used for clinical diagnosis or "
              "treatment decisions.")

PLANES = {"axial": 2, "coronal": 1, "sagittal": 0}
MAX_SCROLL_FRAMES = 72
_CMAP = plt.get_cmap("tab20")


# --------------------------------------------------------------------------
# shared helpers
# --------------------------------------------------------------------------

def region_color_map(mask_data):
    """Stable region-id -> RGB (0-1 floats): i-th smallest label = tab20(i)."""
    labels = sorted(int(l) for l in np.unique(mask_data) if l > 0)
    return {lab: _CMAP(i % 20)[:3] for i, lab in enumerate(labels)}


def _fig_to_b64(fig, dpi=130):
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=dpi, bbox_inches="tight",
                facecolor="white")
    plt.close(fig)
    return base64.b64encode(buf.getvalue()).decode()


def _pil_to_b64(arr, mode):
    buf = io.BytesIO()
    Image.fromarray(arr, mode).save(buf, format="PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


def _pick_slice(mask_data, axis):
    axes = tuple(i for i in range(3) if i != axis)
    areas = mask_data.sum(axis=axes)
    return int(np.argmax(areas)) if areas.max() > 0 else mask_data.shape[axis] // 2


def _slice2d(data, axis, idx):
    sl = [slice(None)] * 3
    sl[axis] = idx
    return np.rot90(data[tuple(sl)])


def _is_ece_positive(t, y, ref_t):
    """Published ECE rule: minimum pre-contrast, peak at or before ref_t,
    monotonically rising before the peak and falling after."""
    y = np.asarray(y, dtype=float)
    if y.max() <= 0:
        return False
    peak = int(np.argmax(y))
    return (int(np.argmin(y)) == 0
            and t[peak] <= ref_t
            and np.all(np.diff(y[:peak + 1]) >= 0)
            and np.all(np.diff(y[peak:]) <= 0))


def _hex(rgb):
    return "#%02x%02x%02x" % tuple(int(round(c * 255)) for c in rgb)


